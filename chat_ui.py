def extract_artifact(response: str) -> str:
    """Extracts markdown code blocks or structured documents for the side panel."""
    code_blocks = re.findall(r'```[a-zA-Z]*\n(.*?)\n```', response, re.DOTALL)
    if code_blocks:
        return code_blocks[-1].strip()
    
    if response.strip().startswith("#"):
        return response.strip()
        
    return "_No specific artifact or code block generated in this response._"

def user_func(user_message, history, model_choice):
    profile = MODEL_PROFILES.get(model_choice, MODEL_PROFILES["Ling-3.0-Flash (Fastest - 124B MoE)"])
    status_text = f"**Active Model:** `{profile['id']}` | **TTFT:** `{profile['ttft']}` | **Throughput:** `{profile['speed']}`"
    return "", history + [[user_message, None]], status_text

def bot_func(history, model_choice):
    user_message = history[-1][0]
    profile = MODEL_PROFILES.get(model_choice, MODEL_PROFILES["Ling-3.0-Flash (Fastest - 124B MoE)"])
    
    clean_func_name = re.sub(r'\W+', '_', user_message.lower())[:20]
    
    # Generate structured output highlighting the selected model
    response = (
        f"**Response from {profile['id']}** ({profile['tag']})\n\n"
        f"Generated with TTFT of **{profile['ttft']}** at **{profile['speed']}**.\n\n"
        f"```python\n"
        f"# Solution generated by {profile['id']}\n"
        f"def solve_{clean_func_name}():\n"
        f"    \"\"\"Automated implementation for: {user_message}\"\"\"\n"
        f"    result = {{'status': 'SUCCESS', 'model': '{profile['id']}', 'speed': '{profile['speed']}'}}\n"
        f"    return result\n"
        f"```\n"
    )
    
    history[-1][1] = response
    artifact = extract_artifact(response)
    
    return history, artifact

